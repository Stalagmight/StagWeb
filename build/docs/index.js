// The user guide: Markdown from docs/user-guide/ in the app repository, built
// into /docs/ on the site. See docs/user-guide-pipeline.md.
//
// Pages are generated into src/docs/ before Vite starts and handed to it as
// ordinary inputs, so the partials, fonts, image fingerprinting and the
// sitemap all treat them like the hand-written pages. src/docs/ is a build
// product: git-ignored and wiped on every run.
import fs from 'node:fs';
import path from 'node:path';
import { buildModel, walk, APP_REPO, SOURCE_IN_REPO } from './model.js';
import { prepareImages } from './images.js';
import { renderPage, renderRedirect } from './templates.js';
import { releaseData } from '../releases-data.js';

export const DEFAULT_SOURCE = '.app/docs/user-guide';
const MARKER = '.generated-by-build-docs';

function report(warnings) {
  for (const { file, msg } of warnings) {
    console.warn(`[docs] ${file}: ${msg}`);
    // Shown on the workflow run and its summary, so a broken cross-reference
    // is visible without failing the deploy of everything else.
    if (process.env.GITHUB_ACTIONS) console.log(`::warning file=${DEFAULT_SOURCE}/${file},title=User guide::${msg}`);
  }
}

export default function docs({ site }) {
  const source = path.resolve(process.env.DOCS_SOURCE || DEFAULT_SOURCE);
  let outDir = null;
  let model = null;
  let currentVersion = null;
  const lastmod = new Map();

  function clean() {
    if (!fs.existsSync(outDir)) return;
    if (!fs.existsSync(path.join(outDir, MARKER))) {
      throw new Error(`[docs] ${outDir} exists but was not generated by build/docs; refusing to delete it`);
    }
    fs.rmSync(outDir, { recursive: true, force: true });
  }

  async function generate() {
    clean();
    lastmod.clear();
    model = null;
    if (!fs.existsSync(source)) {
      console.warn(`[docs] no user guide at ${path.relative(process.cwd(), source) || source}; building without /docs/`);
      return {};
    }
    const data = await releaseData();
    currentVersion = data?.current?.version || null;
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, MARKER), 'Generated by build/docs/. Wiped on every build.\n');
    const images = await prepareImages(source, outDir, walk(source));
    model = buildModel(source, { currentVersion, images });
    if (!model) {
      clean();
      console.warn('[docs] the user guide has no published pages yet; building without /docs/');
      return {};
    }
    report(model.warnings);
    const inputs = {};
    for (const p of model.pages) {
      const file = path.join(outDir, p.route, 'index.html');
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, renderPage(p, model, { site, currentVersion }));
      inputs[`docs/${p.route || 'index'}`.replace(/\/$/, '')] = file;
      if (p.updated) lastmod.set(file, p.updated);
    }
    for (const [rel, info] of model.assets) {
      if (info.optimized) continue;
      const to = path.join(outDir, '_files', rel);
      fs.mkdirSync(path.dirname(to), { recursive: true });
      fs.copyFileSync(path.join(source, rel), to);
    }
    console.log(`[docs] ${model.pages.filter(p => !p.auto).length} pages, ${model.pages.filter(p => p.auto).length} section pages, ${model.redirects.length} redirects, ${model.warnings.length} warnings`);
    return inputs;
  }

  // Links that only exist when the docs do: the nav and footer entries, and a
  // link under each home-page feature to the page that declares it
  // (`feature: <key>` in its front matter).
  function links(html, ctx) {
    const dir = ctx.path.replace(/[^/]*$/, '');
    const root = '../'.repeat(dir.split('/').filter(Boolean).length);
    const inDocs = dir.startsWith('/docs/');
    html = html.replace(/<!--docs-nav-->/g, model
      ? `<li><a href="${root}docs/"${inDocs ? ' aria-current="page"' : ''}>Docs</a></li>` : '');
    html = html.replace(/<!--docs-footer-->/g, model ? `<li><a href="${root}docs/">Documentation</a></li>` : '');
    return html.replace(/<!--docs-more:([a-z0-9-]+)-->/g, (_, key) => {
      const page = model && model.sequence.find(p => String(p.data.feature || '') === key);
      return page
        ? `<a class="ghost-link f-more" href="${root}docs/${page.route}">${page.title.replace(/[&<>"]/g, c => `&#${c.charCodeAt(0)};`)}<span class="ghost-arrow" aria-hidden="true">→</span></a>`
        : '';
    });
  }

  function llms(base) {
    if (!model) return { index: base, full: null };
    const abs = route => `${site}docs/${route}`;
    const sections = model.tree.children.map(n => {
      const list = [n.page, ...model.childrenOf(n.page.route)].filter(p => !p.auto);
      return list.length ? `### ${n.page.title}\n\n${list.map(p => `- [${p.title}](${abs(p.route)})${p.description ? `: ${p.description}` : ''}`).join('\n')}` : '';
    }).filter(Boolean);
    const index = `${base.trimEnd()}\n- [Documentation, all pages in one file](${site}llms-full.txt)\n\n## Documentation\n\n${sections.join('\n\n')}\n`;

    const pages = [model.byRoute.get(''), ...model.sequence].filter(p => p && !p.auto);
    const full = [`# Stalagmight documentation\n\n> The user guide for Stalagmight, free and open-source underwater cave survey software. Every page of ${site}docs/ in one file.\n`];
    for (const p of pages) {
      let body = p.env.leadTitle ? p.body.replace(/^\s*#[ \t]+.*\r?\n/, '') : p.body;
      body = body.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)((?:\s+"[^"]*")?)\)/g, (m, bang, text, href) => {
        if (bang) return `[Image: ${text}]`;
        const res = p.env.resolveLink(href);
        if (res.broken) return text;
        if (res.page) return `[${text}](${abs(res.page.route)}${(res.href.match(/#.*$/) || [''])[0]})`;
        if (href.startsWith('#')) return `[${text}](${abs(p.route)}${href})`;
        if (res.href.startsWith('/') && !res.href.startsWith('//')) return `[${text}](${site}${res.href.slice(1)})`;
        if (res.external || /^[a-z][a-z0-9+.-]*:/i.test(res.href)) return `[${text}](${res.href})`;
        // A file next to the docs: its copy in the repository.
        return `[${text}](${APP_REPO}/blob/master/${SOURCE_IN_REPO}/${path.posix.normalize(path.posix.join(path.posix.dirname(p.rel), href))})`;
      });
      full.push(`---\n\n# ${p.title}\n\nURL: ${abs(p.route)}\n\n${body.trim()}\n`);
    }
    return { index, full: full.join('\n') };
  }

  return {
    name: 'docs',
    async config(cfg) {
      outDir = path.join(path.resolve(cfg.root || '.'), 'docs');
      const inputs = await generate();
      if (Object.keys(inputs).length) return { build: { rollupOptions: { input: inputs } } };
    },
    configureServer(server) {
      if (!fs.existsSync(source)) return;
      server.watcher.add(source);
      let timer = null;
      const regen = file => {
        if (!path.resolve(file).startsWith(source)) return;
        clearTimeout(timer);
        timer = setTimeout(async () => {
          try { await generate(); } catch (e) { console.error(e); }
          server.ws.send({ type: 'full-reload' });
        }, 150);
      };
      for (const ev of ['add', 'change', 'unlink']) server.watcher.on(ev, regen);
    },
    transformIndexHtml: { order: 'post', handler: links },
    generateBundle() {
      const base = fs.readFileSync(path.resolve('src/llms.txt'), 'utf8');
      const { index, full } = llms(base);
      this.emitFile({ type: 'asset', fileName: 'llms.txt', source: index });
      if (full) this.emitFile({ type: 'asset', fileName: 'llms-full.txt', source: full });
      if (!model) return;
      for (const [rel, info] of model.assets) {
        if (info.kind === 'file') this.emitFile({ type: 'asset', fileName: `docs/_files/${rel}`, source: fs.readFileSync(path.join(source, rel)) });
      }
      for (const r of model.redirects) {
        this.emitFile({ type: 'asset', fileName: `docs/${r.from}index.html`, source: renderRedirect(r.from, r.to, site) });
      }
    },
    // For the sitemap: a generated page's date is its Markdown file's last commit
    // in the app repository, not anything in this one.
    lastmodFor: file => lastmod.get(path.resolve(file)),
  };
}
